CREATE TABLE incidents (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                           brand_workspace_id BIGINT NOT NULL,
                           title VARCHAR(500) NOT NULL,
                           description TEXT,
                           severity VARCHAR(20) NOT NULL,
                           status VARCHAR(20) NOT NULL,
                           assigned_to VARCHAR(255),
                           mention_count INT DEFAULT 0,
                           resolution_percent INT DEFAULT 0,
                           requires_immediate_action BOOLEAN DEFAULT FALSE,
                           pattern_keyword VARCHAR(255),
                           detected_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                           resolved_at TIMESTAMP(6) WITH TIME ZONE,
                           created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                           updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
                           PRIMARY KEY (id),
                           CONSTRAINT fk_incidents_brand_workspace FOREIGN KEY (brand_workspace_id) REFERENCES BrandWorkspace(id)
);

CREATE INDEX idx_incidents_workspace_status ON incidents (brand_workspace_id, status);
CREATE INDEX idx_incidents_workspace_action ON incidents (brand_workspace_id, requires_immediate_action);